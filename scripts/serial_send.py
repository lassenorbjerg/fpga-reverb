#!/usr/bin/env python3
"""
Generated by Claude Opus 5

Stream live microphone audio to a UART port.

Captures from the default (or selected) input device and pushes raw PCM
samples out a serial port as fast as the baud rate allows.  Intended as the
host side of the FPGA reverb: the FPGA receives a continuous stream of
samples, no framing, little-endian.

Examples
--------
    python scripts/serial_send.py COM3
    python scripts/serial_send.py COM/3 --baud 2000000
    python scripts/serial_send.py 3 --rate 16000 --bits 8
    python scripts/serial_send.py --list-ports
    python scripts/serial_send.py --list-devices

Requires:  pip install pyserial sounddevice numpy
"""

from __future__ import annotations

import argparse
import queue
import sys
import threading
import time

import numpy as np
import serial
import sounddevice as sd
from serial.tools import list_ports as lp

DEFAULT_BAUD = 115_200
DEFAULT_RATE = 16_000
DEFAULT_BITS = 16
DEFAULT_BLOCK = 256  # frames per audio callback
DEFAULT_MAX_LATENCY = 100.0  # ms of audio allowed to pile up before dropping

# UART frames a byte as 1 start + 8 data + 1 stop bit.
BITS_PER_BYTE_ON_WIRE = 10


def normalize_port(port: str) -> str:
    """Accept sloppy port spellings: "COM/3", "com3", "3" all mean COM3.

    POSIX device paths are passed through untouched.
    """
    p = port.strip()
    if p.startswith("/dev/"):
        return p
    p = p.replace("/", "").replace("\\", "")
    if p.isdigit():
        return f"COM{p}" if sys.platform == "win32" else port.strip()
    if p[:3].upper() == "COM":
        return "COM" + p[3:]
    return port.strip()


def list_ports() -> None:

    ports = list(lp.comports())
    if not ports:
        print("No serial ports found.")
        return
    print("Serial ports:")
    for p in ports:
        print(f"  {p.device:<12} {p.description}")


def list_devices() -> None:

    print(sd.query_devices())


class Stats:
    """Counters shared between the audio callback and the status printer."""

    def __init__(self) -> None:
        self.dropped_blocks = 0
        self.xruns = 0
        self.bytes_sent = 0
        self.peak = 0.0


def build_encoder(bits: int, gain: float):
    """Return a callable turning an int16 mono frame buffer into wire bytes."""

    def encode(block):
        samples = block[:, 0].astype(np.float32) * gain
        peak = (float(np.max(np.abs(samples))) / 32768.0) if samples.size else 0.0
        if bits == 8:
            # Unsigned 8-bit, midpoint 128 -- one sample per UART byte.
            data = np.clip(samples / 256.0 + 128.0, 0, 255).astype(np.uint8)
        else:
            data = np.clip(samples, -32768, 32767).astype("<i2")
        return data.tobytes(), peak

    return encode


def meter(peak: float, width: int = 24) -> str:
    filled = min(width, int(peak * width + 0.5))
    return "#" * filled + "-" * (width - filled)


def run(args: argparse.Namespace) -> int:

    port = normalize_port(args.port) if args.port else None
    bytes_per_sample = 1 if args.bits == 8 else 2
    wire_bps = args.rate * bytes_per_sample * BITS_PER_BYTE_ON_WIRE

    if not args.no_serial:
        if args.baud < wire_bps:
            print(
                f"error: {args.baud} baud carries {args.baud // BITS_PER_BYTE_ON_WIRE} B/s, "
                f"but {args.rate} Hz x {bytes_per_sample} B needs "
                f"{args.rate * bytes_per_sample} B/s ({wire_bps} baud minimum).\n"
                f"       Raise --baud, lower --rate, or use --bits 8.",
                file=sys.stderr,
            )
            return 2
        if args.baud < wire_bps * 1.05:
            print(
                f"warning: only {args.baud / wire_bps:.0%} headroom over the required "
                f"{wire_bps} baud; expect dropped audio.",
                file=sys.stderr,
            )

    # Queue depth is bounded by the latency budget, so a link that cannot keep
    # up drops audio instead of drifting further and further behind real time.
    max_blocks = max(2, int(args.max_latency / 1000.0 * args.rate / args.block))
    q: queue.Queue[bytes] = queue.Queue(maxsize=max_blocks)
    stats = Stats()
    stop = threading.Event()
    encode = build_encoder(args.bits, args.gain)

    def callback(indata, frames, time_info, status):
        if status:
            stats.xruns += 1
        payload, peak = encode(indata)
        stats.peak = max(stats.peak, peak)
        try:
            q.put_nowait(payload)
        except queue.Full:
            # Drop the stalest block; staying current matters more than
            # delivering every sample.
            try:
                q.get_nowait()
            except queue.Empty:
                pass
            stats.dropped_blocks += 1
            try:
                q.put_nowait(payload)
            except queue.Full:
                pass

    ser = None
    if not args.no_serial:
        try:
            ser = serial.Serial(port, args.baud, timeout=1)
        except serial.SerialException as exc:
            print(f"error: could not open {port}: {exc}", file=sys.stderr)
            print(
                "       run with --list-ports to see what is available.",
                file=sys.stderr,
            )
            return 1

    def writer():
        while not stop.is_set():
            try:
                chunk = q.get(timeout=0.2)
            except queue.Empty:
                continue
            if ser is not None:
                try:
                    # Blocking write; the serial port paces this thread.
                    ser.write(chunk)
                except serial.SerialException as exc:
                    print(f"\nerror: write failed: {exc}", file=sys.stderr)
                    stop.set()
                    return
            stats.bytes_sent += len(chunk)

    writer_thread = threading.Thread(target=writer, name="uart-writer", daemon=True)
    writer_thread.start()

    target = (
        f"{port} @ {args.baud} baud"
        if ser is not None
        else "(--no-serial, nothing sent)"
    )
    buffered_ms = max_blocks * args.block / args.rate * 1000
    print(
        f"{args.rate} Hz mono, {args.bits}-bit -> {target} "
        f"({args.block}-frame blocks, {buffered_ms:.0f} ms buffer)"
    )
    print("Ctrl-C to stop.\n")

    started = time.monotonic()
    last_report = 0.0
    try:
        with sd.InputStream(
            samplerate=args.rate,
            blocksize=args.block,
            device=args.device,
            channels=1,
            dtype="int16",
            callback=callback,
        ):
            while not stop.is_set():
                time.sleep(0.1)
                now = time.monotonic()
                if now - last_report < 0.25:
                    continue
                last_report = now
                sys.stdout.write(
                    f"\r[{meter(stats.peak)}] {stats.bytes_sent / 1024:8.1f} KiB  "
                    f"queue {q.qsize():2d}/{max_blocks}  "
                    f"dropped {stats.dropped_blocks}  xruns {stats.xruns}   "
                )
                sys.stdout.flush()
                stats.peak = 0.0
    except KeyboardInterrupt:
        pass
    except sd.PortAudioError as exc:
        print(f"\nerror: audio device: {exc}", file=sys.stderr)
        return 1
    finally:
        stop.set()
        writer_thread.join(timeout=1.0)
        if ser is not None:
            ser.close()

    elapsed = time.monotonic() - started
    print(
        f"\n\nSent {stats.bytes_sent / 1024:.1f} KiB in {elapsed:.1f} s "
        f"({stats.bytes_sent / max(elapsed, 1e-9) / 1024:.1f} KiB/s), "
        f"{stats.dropped_blocks} blocks dropped, {stats.xruns} xruns."
    )
    return 0


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Stream microphone audio out a UART port in real time.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "port",
        nargs="?",
        help='serial port: "COM3", "COM/3", "3", or "/dev/ttyUSB0"',
    )
    parser.add_argument(
        "-b", "--baud", type=int, default=DEFAULT_BAUD, help="baud rate"
    )
    parser.add_argument(
        "-r", "--rate", type=int, default=DEFAULT_RATE, help="sample rate in Hz"
    )
    parser.add_argument(
        "--bits",
        type=int,
        choices=(8, 16),
        default=DEFAULT_BITS,
        help="8 = unsigned 8-bit, 16 = signed 16-bit little-endian",
    )
    parser.add_argument(
        "--block", type=int, default=DEFAULT_BLOCK, help="frames per audio callback"
    )
    parser.add_argument(
        "--max-latency",
        type=float,
        default=DEFAULT_MAX_LATENCY,
        help="ms of audio to buffer before dropping blocks",
    )
    parser.add_argument(
        "-g", "--gain", type=float, default=1.0, help="linear input gain"
    )
    parser.add_argument(
        "-d",
        "--device",
        help="input device index or name substring (default: system default)",
    )
    parser.add_argument(
        "--list-ports", action="store_true", help="list serial ports and exit"
    )
    parser.add_argument(
        "--list-devices", action="store_true", help="list audio devices and exit"
    )
    parser.add_argument(
        "--no-serial",
        action="store_true",
        help="capture and meter only, without opening a port (mic check)",
    )
    args = parser.parse_args(argv)

    if args.device is not None and args.device.isdigit():
        args.device = int(args.device)
    return args


def main(argv=None) -> int:
    args = parse_args(argv)

    try:
        if args.list_ports:
            list_ports()
            return 0
        if args.list_devices:
            list_devices()
            return 0

        if not args.port and not args.no_serial:
            print(
                "error: no port given. Try --list-ports, or --no-serial to test the mic. For help -h",
                file=sys.stderr,
            )
            return 2

        return run(args)
    except ImportError as exc:
        print(f"error: missing dependency: {exc.name}", file=sys.stderr)
        print("       pip install pyserial sounddevice numpy", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
