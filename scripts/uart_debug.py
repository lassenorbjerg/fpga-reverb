def heading(text: str) -> None:
    print(f"\n{text}\n{'-' * len(text)}")


def mode_check(args) -> int:
    heading("Baud rate")
    report = divider_report(args.clock, args.baud, args.verilog)
    warnings = print_divider_report(report)

    heading("Wire format")
    data = bytes(int(b, 0) for b in args.bytes) if args.bytes else b"U\x00"
    print_wire_format(data, args.baud, args.stopbits, args.cols)

    heading("Verdict")
    for w in warnings:
        print(f"  WARNING  {w}")
    if not warnings:
        print("  The framing maths checks out. Run --mode selftest against the board "
              "to confirm the wire agrees.")
    return 1 if warnings else 0


def mode_selftest(args) -> int:
    names = list(PATTERNS) if args.pattern == "all" else [args.pattern]

    heading("Baud rate")
    report = divider_report(args.clock, args.baud, args.verilog)
    warnings = print_divider_report(report)

    heading(f"Echo test  ({args.port or 'loop://'} @ {args.baud:,} baud, "
            f"{args.length} bytes per pattern)")
    try:
        ser = open_port(args, framing=args.framing)
    except serial.SerialException as exc:
        print(f"error: could not open port: {exc}", file=sys.stderr)
        print("       run with --list-ports to see what is available.", file=sys.stderr)
        return 1

    results: list[tuple[str, dict]] = []
    try:
        for name in names:
            payload = build_pattern(name, args.length, args.seed)
            received, elapsed = exchange(ser, payload, args.baud, args.gap)
            stats = analyse(payload, received)
            results.append((name, stats))

            status = "ok  " if stats["clean"] else "FAIL"
            rate = len(received) / elapsed if elapsed else 0.0
            print(f"  {status} {name:<8} {stats['ok']}/{stats['sent']} bytes exact, "
                  f"{len(stats['subs'])} corrupt, {stats['drops']} lost")
            print(f"       {PATTERN_HELP[name]}")
            # loop:// is a software buffer and ignores the baud rate, so the
            # share-of-the-wire figure would be nonsense there.
            share = ("" if args.loop else
                     f" ({rate / (args.baud / FRAME_BITS):.0%} of the "
                     f"{args.baud:,} baud ceiling)")
            print(f"       {rate / 1024:.1f} KiB/s{share}, "
                  f"round trip {elapsed * 1000:.1f} ms")
            if stats["subs"]:
                index, want, got = stats["subs"][0]
                print(f"       first bad byte @{index}: sent 0x{want:02x} "
                      f"got 0x{got:02x}  (xor 0x{want ^ got:02x})")
            print()
    except KeyboardInterrupt:
        print("\ninterrupted.")
    finally:
        ser.close()

    if any(r["subs"] for _, r in results):
        heading("Which bits went wrong")
        totals = [sum(r["bit_errors"][b] for _, r in results) for b in range(8)]
        print("  Later bits are sampled further from the start edge, so clock drift")
        print("  piles up at the top of the byte while noise spreads evenly.")
        print()
        for row in bit_bar(totals):
            print(row)

    heading("Diagnosis")
    for note in warnings:
        print(f"  WARNING  {note}")
    for note in diagnose(results, args.baud):
        print(f"  * {note}")

    clean = all(r["clean"] for _, r in results)
    return 0 if clean and not warnings else 1


def mode_sweep(args) -> int:
    bauds = args.sweep_bauds or list(STANDARD_BAUDS)
    payload = build_pattern(args.pattern if args.pattern != "all" else "ramp",
                            min(args.length, 64), args.seed)

    heading(f"Baud sweep  ({args.port or 'loop://'}, {len(payload)} bytes each)")
    print(f"  {'baud':>9}  {'exact':>7}  {'lost':>5}  result")
    best: list[tuple[float, int]] = []
    for baud in bauds:
        try:
            ser = open_port(args, baud=baud, framing=args.framing)
        except (serial.SerialException, ValueError) as exc:
            print(f"  {baud:>9,}  {'-':>7}  {'-':>5}  not supported ({exc})")
            continue
        try:
            received, _ = exchange(ser, payload, baud, args.gap)
        except serial.SerialException as exc:
            print(f"  {baud:>9,}  {'-':>7}  {'-':>5}  read failed ({exc})")
            continue
        finally:
            ser.close()

        stats = analyse(payload, received)
        score = stats["ok"] / stats["sent"]
        best.append((score, baud))
        verdict = "clean" if stats["clean"] else ("partial" if score > 0.1 else "no")
        print(f"  {baud:>9,}  {stats['ok']:>3}/{stats['sent']:<3}  "
              f"{stats['drops']:>5}  {verdict}")

    heading("Verdict")
    winners = [b for s, b in best if s >= 0.99]
    if not winners:
        print("  No baud rate echoed cleanly. Check the board is programmed and that")
        print("  tx/rx are the right way round before trusting any of this.")
        return 1
    print(f"  Clean at: {', '.join(f'{b:,}' for b in winners)}")
    if args.baud not in winners:
        print(f"  Note: --baud {args.baud:,} is NOT among them. The bitstream is "
              f"running at {winners[0]:,}.")
        return 1
    print(f"  --baud {args.baud:,} is among them, as expected.")
    return 0


def mode_framing(args) -> int:
    configs = args.framing_list or ["8N1", "8N2", "8E1", "8O1", "7N1"]
    payload = build_pattern("framing", min(args.length, 64), args.seed)

    heading(f"Framing sweep  ({args.port or 'loop://'} @ {args.baud:,} baud)")
    print("  The FPGA sends 8N1 (chisel-lib shifts out 1 start, 8 data, 2 stop bits,")
    print("  so a host set to 1 stop bit also works -- it just sees extra idle).")
    print()
    print(f"  {'config':>7}  {'exact':>7}  result")
    passed = []
    for cfg in configs:
        try:
            ser = open_port(args, framing=cfg)
        except (serial.SerialException, ValueError, KeyError) as exc:
            print(f"  {cfg:>7}  {'-':>7}  not supported ({exc})")
            continue
        try:
            received, _ = exchange(ser, payload, args.baud, args.gap)
        except serial.SerialException as exc:
            print(f"  {cfg:>7}  {'-':>7}  read failed ({exc})")
            continue
        finally:
            ser.close()

        stats = analyse(payload, received)
        if stats["clean"]:
            passed.append(cfg)
        print(f"  {cfg:>7}  {stats['ok']:>3}/{stats['sent']:<3}  "
              f"{'clean' if stats['clean'] else 'corrupt'}")

    heading("Verdict")
    if "8N1" in passed:
        print("  8N1 is clean, which is what the FPGA emits.")
        if "7N1" in passed:
            print("  7N1 also passed -- expected when the payload has no bit 7 set.")
        return 0
    if passed:
        print(f"  8N1 failed but {', '.join(passed)} passed. The host and the FPGA")
        print("  disagree about framing; match the host to whatever the FPGA emits.")
    else:
        print("  Nothing passed. This is a baud or wiring problem, not a framing one")
        print("  -- run --mode sweep first.")
    return 1


def mode_monitor(args) -> int:
    try:
        ser = open_port(args, framing=args.framing, timeout=0.05)
    except serial.SerialException as exc:
        print(f"error: could not open port: {exc}", file=sys.stderr)
        return 1

    ceiling = args.baud / FRAME_BITS
    # "all" means every pattern in the echo test; here one has to be picked.
    pattern = "ramp" if args.pattern == "all" else args.pattern
    expect = build_pattern(pattern, args.length, args.seed) if args.send else None

    if args.seconds:
        how = f"for {args.seconds:g} s"
    elif args.hold:
        how = "while you hold SPACE (release to stop, q to quit)"
    else:
        how = "until Ctrl-C"
    heading(f"Monitor  ({args.port or 'loop://'} @ {args.baud:,} baud, {how})")
    if args.send:
        print(f"  driving the link with the '{pattern}' pattern and checking the echo")
    print()

    total = bytearray()
    sent_total = 0
    errors = 0
    started = None
    stopped = None
    last_status = 0.0
    recording = not args.hold
    last_key = 0.0

    try:
        with KeyWatcher() as keys:
            if args.hold:
                print("  waiting for SPACE...", end="\r")
            while True:
                now = time.monotonic()

                if args.hold:
                    pressed = keys.drain()
                    if "q" in pressed.lower():
                        stopped = now
                        break
                    if " " in pressed:
                        last_key = now
                        if not recording:
                            recording = True
                            started = now
                            total.clear()
                            print(" " * 40, end="\r")
                    elif recording and now - last_key > HOLD_GAP:
                        # The release is only noticed once the auto-repeat
                        # lapses, so the last keypress is the real end.
                        stopped = last_key
                        break

                if recording and started is None:
                    started = now
                if recording and args.send and expect:
                    # Keep roughly one wire-time of data in flight, no more.
                    if ser.out_waiting < len(expect):
                        ser.write(expect)
                        sent_total += len(expect)

                chunk = ser.read(ser.in_waiting or 1)
                if chunk and recording:
                    total += chunk

                if recording and now - last_status > 0.25:
                    last_status = now
                    elapsed = max(1e-6, now - started)
                    rate = len(total) / elapsed
                    tail = " ".join(f"{b:02x}" for b in total[-8:])
                    share = "" if args.loop else f"{rate / ceiling:4.0%} of wire  "
                    sys.stdout.write(
                        f"\r  {elapsed:5.1f}s  {len(total) / 1024:8.1f} KiB  "
                        f"{rate / 1024:7.1f} KiB/s  {share}"
                        f"last: {tail:<23}"
                    )
                    sys.stdout.flush()

                if args.seconds and recording and now - started >= args.seconds:
                    stopped = now
                    break
    except KeyboardInterrupt:
        stopped = time.monotonic()
    finally:
        ser.close()

    elapsed = max(1e-6, (stopped or time.monotonic()) - started) if started else 0.0
    heading("Captured")
    if not total:
        print("  Nothing arrived. The FPGA only echoes what it is sent -- pass --send")
        print("  to drive it, or run --mode selftest.")
        return 1

    rate = len(total) / elapsed
    print(f"  {len(total):,} bytes in {elapsed:.2f} s")
    if args.loop:
        print(f"  {rate:,.0f} B/s (loop:// is a software buffer; it ignores the baud rate)")
    else:
        print(f"  {rate:,.0f} B/s = {rate * FRAME_BITS:,.0f} baud equivalent "
              f"({rate / ceiling:.0%} of the {args.baud:,} baud ceiling)")

    if args.send and expect:
        print(f"  {sent_total:,} bytes sent")
        # The echo repeats the pattern endlessly, so the capture can start
        # anywhere in it; find where before comparing.
        offset = (expect * 2).find(bytes(total[:16])) if len(total) >= 16 else 0
        if offset < 0:
            print("  No part of the capture lines up with the pattern, so there is")
            print("  nothing to compare against. Run --mode sweep -- this is what a")
            print("  baud mismatch looks like.")
            errors = len(total)
        else:
            reference = (expect * (len(total) // len(expect) + 2))
            stats = analyse(reference[offset : offset + len(total)], bytes(total))
            errors = len(stats["subs"])
            print(f"  {stats['ok']:,}/{len(total):,} bytes matched the pattern, "
                  f"{errors} corrupt, {stats['drops']} lost")
            if stats["subs"]:
                print()
                for row in bit_bar(stats["bit_errors"]):
                    print(row)

    distinct = len(set(total))
    print(f"  {distinct} distinct byte values"
          f"{'  (suspiciously few -- a stuck line looks like this)' if distinct <= 2 else ''}")
    if args.save:
        with open(args.save, "wb") as fh:
            fh.write(total)
        print(f"  written to {args.save}")
    return 0 if not errors else 1


MODE_FUNCS = {
    "check": mode_check,
    "selftest": mode_selftest,
    "sweep": mode_sweep,
    "framing": mode_framing,
    "monitor": mode_monitor,
}


