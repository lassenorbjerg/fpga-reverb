PATTERNS = ("ramp", "framing", "alt", "walk", "random")

PATTERN_HELP = {
    "ramp": "0,1,2,... every byte differs from its neighbours, so a drop shows up",
    "framing": "0xFF/0x00, the longest high and low runs a frame can make",
    "alt": "0x55/0xAA, maximum transition density",
    "walk": "one bit set, then one bit clear, to find a stuck lane",
    "random": "reproducible pseudo-random bytes",
}


def build_pattern(name: str, length: int, seed: int = 1) -> bytes:
    """Patterns chosen so that *which* one fails tells you *what* is wrong."""
    if name == "ramp":
        return bytes(i & 0xFF for i in range(length))
    if name == "framing":
        # 0x00 holds the line low for 9 bit times -- the longest low run a
        # frame can produce and the hardest case for start-bit resync.  0xFF
        # is the opposite: the start bit is the only low bit in the frame.
        return bytes((0x00 if i % 2 else 0xFF) for i in range(length))
    if name == "alt":
        return bytes((0x55 if i % 2 else 0xAA) for i in range(length))
    if name == "walk":
        vals = [1 << (i % 8) for i in range(8)]
        vals += [0xFF ^ (1 << (i % 8)) for i in range(8)]
        return bytes(vals[i % len(vals)] for i in range(length))
    if name == "random":
        return bytes(random.Random(seed).randrange(256) for _ in range(length))
    raise ValueError(f"unknown pattern {name!r}")


