#!/usr/bin/env python3
"""
Generated by Claude Opus 5

Debug a UART link: framing, baud rate, and what actually survives the wire.

Five modes, from "no hardware needed" to "watch it live":

    check     Offline framing maths.  Works out the FPGA's real bit period
              from the clock and the generated Verilog, prints the baud
              error and the drift budget, and draws the start/data/stop bits
              of a byte as an ASCII waveform.  No board required.
    selftest  Drives the board with patterns chosen to break specific things
              (0x00/0xFF stress start/stop detection, 0x55/0xAA stress
              transition density, a ramp exposes dropped bytes), reads the
              echo back and names the likely fault.
    sweep     Echoes a short pattern at a list of baud rates and reports
              which come back clean -- finds the baud the bitstream actually
              uses when you are not sure.
    framing   The same idea across framing configs (8N1, 8N2, 7N1, 8E1) to
              pin down a stop-bit or parity mismatch.
    monitor   Real-time capture: for a fixed number of seconds, for as long
              as you hold SPACE, or until Ctrl-C.

A USB-serial adapter decodes start and stop bits in hardware and never hands
them to the host, so no host-side script can literally show you those edges --
that needs a scope or a logic analyser.  What this script does instead is
check the maths that produces the bits, then hammer the link with the patterns
that fail first when the maths is wrong.  "check" says whether the bits should
be right; "selftest" says whether they are.

Examples
--------
    python scripts/uart_debug.py --mode check
    python scripts/uart_debug.py COM3
    python scripts/uart_debug.py COM3 --baud 921600 --pattern framing
    python scripts/uart_debug.py COM3 --mode sweep
    python scripts/uart_debug.py COM3 --mode framing
    python scripts/uart_debug.py COM3 --mode monitor --seconds 5
    python scripts/uart_debug.py COM3 --mode monitor --hold
    python scripts/uart_debug.py --loop            # no board, exercise the script
    python scripts/uart_debug.py --list-ports

Requires:  pip install pyserial
"""

