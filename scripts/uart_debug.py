HOLD_GAP = 0.7  # longer than the OS auto-repeat delay, so a real hold never lapses


class KeyWatcher:
    """Non-blocking console key reads, for "record while SPACE is held".

    A console only delivers key-press events, never key-release, so a hold is
    inferred from the key auto-repeating.  The OS waits about half a second
    before the first repeat, which is why a tap still records ~HOLD_GAP.
    """

    def __init__(self) -> None:
        self.win = sys.platform == "win32"
        self._fd = None
        self._saved = None
        if self.win:
            import msvcrt  # noqa: PLC0415 -- Windows only
            self._msvcrt = msvcrt

    def __enter__(self):
        if not self.win and sys.stdin.isatty():
            import termios
            import tty
            self._fd = sys.stdin.fileno()
            self._saved = termios.tcgetattr(self._fd)
            tty.setcbreak(self._fd)
        return self

    def __exit__(self, *exc):
        if self._saved is not None:
            import termios
            termios.tcsetattr(self._fd, termios.TCSADRAIN, self._saved)
        return False

    def drain(self) -> str:
        """Every key waiting right now, as a string (empty if none)."""
        out = []
        if self.win:
            while self._msvcrt.kbhit():
                ch = self._msvcrt.getwch()
                if ch in ("\x00", "\xe0"):  # function/arrow key: swallow the pair
                    self._msvcrt.getwch()
                    continue
                out.append(ch)
        elif self._fd is not None:
            import select
            while select.select([sys.stdin], [], [], 0)[0]:
                out.append(sys.stdin.read(1))
        return "".join(out)


