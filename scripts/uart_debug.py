PARITIES = {
    "N": serial.PARITY_NONE,
    "E": serial.PARITY_EVEN,
    "O": serial.PARITY_ODD,
}


def open_port(args, baud: int | None = None, framing: str = "8N1", timeout: float = 0.2):
    """Open the port (or pyserial's loopback) with the given 8N1-style framing."""
    bits, parity, stop = int(framing[0]), framing[1].upper(), int(framing[2])
    kwargs = dict(
        baudrate=baud or args.baud,
        bytesize=bits,
        parity=PARITIES[parity],
        stopbits=serial.STOPBITS_TWO if stop == 2 else serial.STOPBITS_ONE,
        timeout=timeout,
    )
    if args.loop:
        return serial.serial_for_url("loop://", **kwargs)
    return serial.Serial(normalize_port(args.port), **kwargs)


def exchange(ser, payload: bytes, baud: int, gap: float = 0.0,
             settle: float = 0.05) -> tuple[bytes, float]:
    """Send ``payload``, read the echo back, return (received, seconds).

    Waits a full wire-time plus ``settle`` after the last byte, so a slow or
    partially corrupted reply is still collected rather than cut short.
    """
    ser.reset_input_buffer()
    ser.reset_output_buffer()
    wire_time = len(payload) * FRAME_BITS / baud

    start = time.perf_counter()
    if gap:
        for byte in payload:
            ser.write(bytes([byte]))
            ser.flush()
            time.sleep(gap)
    else:
        ser.write(payload)
        ser.flush()

    received = bytearray()
    deadline = time.perf_counter() + 2 * wire_time + len(payload) * gap + settle + 0.25
    while len(received) < len(payload) and time.perf_counter() < deadline:
        chunk = ser.read(max(1, len(payload) - len(received)))
        if chunk:
            received += chunk
            deadline = time.perf_counter() + settle + 0.1  # keep going while it flows
    return bytes(received), time.perf_counter() - start


