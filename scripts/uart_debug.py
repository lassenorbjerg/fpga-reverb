def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Debug a UART link: framing, baud rate, and what gets through.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        epilog="Patterns: " + "; ".join(f"{k} = {v}" for k, v in PATTERN_HELP.items()),
    )
    parser.add_argument("port", nargs="?",
                        help='serial port: "COM3", "COM/3", "3", or "/dev/ttyUSB0"')
    parser.add_argument("-m", "--mode", choices=MODES, default="selftest",
                        help="which test to run")
    parser.add_argument("-b", "--baud", type=int, default=None,
                        help=f"baud rate (default: read from {DEFAULT_VERILOG}, "
                             f"else {DEFAULT_BAUD})")
    parser.add_argument("--clock", type=float, default=DEFAULT_CLOCK,
                        help="FPGA system clock in Hz, for the divider maths")
    parser.add_argument("--verilog", default=DEFAULT_VERILOG,
                        help="generated Verilog to read the real bit period from")

    parser.add_argument("-p", "--pattern", choices=(*PATTERNS, "all"), default="all",
                        help="test pattern to send")
    parser.add_argument("-n", "--length", type=int, default=256,
                        help="bytes per pattern")
    parser.add_argument("--seed", type=int, default=1,
                        help="seed for the random pattern")
    parser.add_argument("--gap", type=float, default=0.0,
                        help="seconds to wait between bytes (0 = send back to back)")
    parser.add_argument("--framing", default="8N1",
                        help="host framing as <data><parity><stop>, e.g. 8N1, 8N2, 8E1")
    parser.add_argument("--framing-list", nargs="+", metavar="CFG",
                        help="framing configs for --mode framing")
    parser.add_argument("--sweep-bauds", nargs="+", type=int, metavar="BAUD",
                        help="baud rates for --mode sweep")

    parser.add_argument("--seconds", type=float,
                        help="--mode monitor: record for this many seconds")
    parser.add_argument("--hold", action="store_true",
                        help="--mode monitor: record only while SPACE is held")
    parser.add_argument("--send", action="store_true",
                        help="--mode monitor: keep sending the pattern and check the echo")
    parser.add_argument("--save", metavar="FILE",
                        help="--mode monitor: write the captured bytes to a file")

    parser.add_argument("--bytes", nargs="+", metavar="BYTE",
                        help="--mode check: bytes to draw, e.g. 0x55 0x00 65")
    parser.add_argument("--cols", type=int, default=6,
                        help="--mode check: characters per bit in the waveform")

    parser.add_argument("--loop", action="store_true",
                        help="use pyserial's loop:// port instead of hardware")
    parser.add_argument("--list-ports", action="store_true",
                        help="list serial ports and exit")

    args = parser.parse_args(argv)
    args.clock = int(args.clock)
    args.stopbits = int(args.framing[2]) if len(args.framing) > 2 else 1

    if args.baud is None:
        # The bitstream's baud beats a hard-coded default: running the debugger
        # at the wrong baud is the exact bug it exists to find.
        from_verilog = project_baud(args.clock, args.verilog)
        args.baud = from_verilog or DEFAULT_BAUD
        args.baud_source = (f"from {os.path.basename(args.verilog)}"
                            if from_verilog else "default")
    else:
        args.baud_source = "from --baud"
    return args


def main(argv=None) -> int:
    args = parse_args(argv)

    if args.list_ports:
        list_ports()
        return 0
    if args.mode != "check" and not args.port and not args.loop:
        print("error: no port given. Try --list-ports, --loop, or --mode check.",
              file=sys.stderr)
        return 2
    if args.hold and args.seconds:
        print("error: --hold and --seconds both set a recording length; pick one.",
              file=sys.stderr)
        return 2

    print(f"uart_debug  mode={args.mode}  baud={args.baud:,} ({args.baud_source})"
          f"  framing={args.framing}")
    try:
        return MODE_FUNCS[args.mode](args)
    except serial.SerialException as exc:
        print(f"\nerror: serial failure: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
