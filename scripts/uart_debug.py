RESYNC_WINDOW = 8  # how far to look for the stream picking up again
RESYNC_CONFIRM = 3  # bytes that must also line up before believing it


def _aligns(sent: bytes, i: int, received: bytes, j: int) -> bool:
    """Do these two positions agree for the next few bytes as well?

    One byte matching by chance is common -- in a ramp, flipping bit 0 of
    byte 20 produces byte 21 -- so a resync is only believed if the bytes
    after it line up too.
    """
    n = min(RESYNC_CONFIRM, len(sent) - i, len(received) - j)
    return n > 0 and all(sent[i + k] == received[j + k] for k in range(n))


def analyse(sent: bytes, received: bytes, window: int = RESYNC_WINDOW) -> dict:
    """Align ``received`` against ``sent``, tolerating dropped or extra bytes.

    An index-by-index compare calls everything after one dropped byte corrupt,
    which buries the real fault.  Resynchronising within a small window keeps
    "a byte went missing" apart from "every byte is wrong".
    """
    i = j = 0
    ok = 0
    drops = 0
    inserts = 0
    subs: list[tuple[int, int, int]] = []
    bit_errors = [0] * 8

    while i < len(sent) and j < len(received):
        if sent[i] == received[j]:
            ok += 1
            i += 1
            j += 1
            continue
        resync = None
        for d in range(1, window + 1):
            if i + d < len(sent) and _aligns(sent, i + d, received, j):
                resync = ("drop", d)
                break
            if j + d < len(received) and _aligns(sent, i, received, j + d):
                resync = ("insert", d)
                break
        if resync is None:  # real corruption, not a slip
            wrong = sent[i] ^ received[j]
            subs.append((i, sent[i], received[j]))
            for b in range(8):
                if wrong >> b & 1:
                    bit_errors[b] += 1
            i += 1
            j += 1
        elif resync[0] == "drop":
            drops += resync[1]
            i += resync[1]
        else:
            inserts += resync[1]
            j += resync[1]

    return {
        "sent": len(sent),
        "received": len(received),
        "ok": ok,
        "subs": subs,
        "bit_errors": bit_errors,
        "drops": drops + max(0, len(sent) - i),
        "inserts": inserts + max(0, len(received) - j),
        "clean": ok == len(sent) == len(received),
        "error_rate": 1.0 - ok / len(sent) if sent else 0.0,
    }


def bit_bar(counts: list[int], width: int = 20) -> list[str]:
    """One row per data bit, so a lopsided error profile is visible at a glance."""
    peak = max(counts) or 1
    rows = []
    for b in range(8):
        filled = int(counts[b] / peak * width + 0.5) if counts[b] else 0
        tag = " (LSB, sent first)" if b == 0 else " (MSB, sent last)" if b == 7 else ""
        rows.append(f"    bit {b}  {'#' * filled:<{width}} {counts[b]:>6}{tag}")
    return rows


def diagnose(results: list[tuple[str, dict]], baud: int) -> list[str]:
    """Turn the error signature into plain-language suspects."""
    notes: list[str] = []
    total_sent = sum(r["sent"] for _, r in results)
    total_recv = sum(r["received"] for _, r in results)
    total_ok = sum(r["ok"] for _, r in results)
    total_subs = sum(len(r["subs"]) for _, r in results)
    total_drops = sum(r["drops"] for _, r in results)
    bits = [sum(r["bit_errors"][b] for _, r in results) for b in range(8)]
    failed = {name for name, r in results if not r["clean"]}

    if total_recv == 0:
        notes.append(
            "Nothing came back at all. Check that the board is programmed, that the "
            "port is the right one, and that tx/rx are not swapped -- in "
            "EchoDemo.scala io.tx is driven by the UART and uart.io.rxd by io.rx."
        )
        return notes

    if total_ok == 0:
        notes.append(
            f"Bytes are arriving ({total_recv} of them) but not one is correct. That "
            f"is a baud-rate mismatch rather than a dead link -- run --mode sweep to "
            f"find the rate the bitstream is actually using."
        )

    if total_subs:
        # A lane wrong in every corrupted byte is a different fault from a
        # timing profile, so test for it before describing the spread.
        stuck = [b for b in range(8) if bits[b] == total_subs]
        if stuck:
            lanes = ", ".join(map(str, stuck))
            notes.append(
                f"bit {lanes} {'is' if len(stuck) == 1 else 'are'} wrong in every "
                f"corrupted byte -- that lane looks stuck or inverted rather than "
                f"merely noisy. More likely a packing bug than the UART itself."
            )
        else:
            late = sum(bits[5:])
            early = sum(bits[:3])
            if late > 3 * max(early, 1):
                notes.append(
                    "Corruption sits in the high bits, which are sampled furthest "
                    "from the start edge. That is the signature of a baud-rate "
                    "mismatch or clock drift, not noise. Run --mode check and "
                    "--mode sweep."
                )
            elif early > 3 * max(late, 1):
                notes.append(
                    "Corruption sits in the low bits, right after the start edge. "
                    "Suspect a noisy or slow falling edge, or a start-bit resync "
                    "problem."
                )
            else:
                notes.append(
                    "Corruption is spread across the bits, which looks like noise or "
                    "marginal signal integrity rather than a timing error."
                )

    if total_drops:
        share = total_drops / total_sent
        notes.append(
            f"{total_drops} byte(s) ({share:.1%}) went missing. With no flow control "
            f"this is usually the receiver being overrun: the echo FIFO on the FPGA "
            f"filling up, or the host not draining fast enough. Try --gap to space "
            f"the bytes out, or a lower --baud."
        )

    if "framing" in failed and failed <= {"framing"}:
        notes.append(
            "Only the 0xFF/0x00 pattern fails. Those hold the line at one level for "
            "a whole frame, so the start/stop edges are the only thing to sync on -- "
            "look at the stop bit and the idle level (--mode framing)."
        )
    if "alt" in failed and failed <= {"alt"}:
        notes.append(
            "Only the 0x55/0xAA pattern fails. That is the highest transition rate "
            f"on the wire; at {baud:,} baud suspect cable length, slew rate or "
            f"a marginal adapter rather than the FPGA."
        )
    if not failed:
        notes.append("Every pattern came back byte-for-byte. The link is clean.")
    return notes


