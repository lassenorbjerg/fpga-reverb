def frame_sequence(data: bytes, stopbits: int = 1) -> list[tuple[str, int]]:
    """The line levels a UART puts out for ``data``, as (label, level)."""
    seq: list[tuple[str, int]] = [("idle", 1)]
    for byte in data:
        seq.append(("S", 0))
        for i in range(8):  # LSB first
            seq.append((str(i), (byte >> i) & 1))
        for _ in range(stopbits):
            seq.append(("P", 1))
    seq.append(("idle", 1))
    return seq


def render_waveform(seq, cols: int = 6, width: int = 96) -> str:
    """Two-row ASCII timing diagram: high on the top row, low on the bottom."""
    total = len(seq) * cols
    top = [" "] * total
    bot = [" "] * total
    lab = [" "] * total

    for i, (label, level) in enumerate(seq):
        start = i * cols
        row = top if level else bot
        for c in range(start, start + cols):
            row[c] = "_"
        if i and seq[i - 1][1] != level:  # draw the edge in both rows
            top[start] = "|"
            bot[start] = "|"
        text = label[:cols]
        off = start + max(0, (cols - len(text)) // 2)
        lab[off : off + len(text)] = list(text)

    chunks = []
    for c in range(0, total, width):
        chunks.append("".join(lab[c : c + width]).rstrip())
        chunks.append("".join(top[c : c + width]).rstrip())
        chunks.append("".join(bot[c : c + width]).rstrip())
        chunks.append("")
    return "\n".join(chunks)


def print_wire_format(data: bytes, baud: int, stopbits: int, cols: int) -> None:
    bit_us = 1e6 / baud
    shown = " ".join(f"0x{b:02x}" for b in data)
    printable = "".join(chr(b) if 32 <= b < 127 else "." for b in data)
    print(f"  bytes             {shown}   |{printable}|")
    print(f"  framing           1 start + 8 data (LSB first) + {stopbits} stop, no parity")
    print(f"  bit time          {bit_us:.3f} us     frame {bit_us * FRAME_BITS:.3f} us")
    print(f"  max throughput    {baud / FRAME_BITS:,.0f} B/s")
    print()
    print("  S = start (always low)    0-7 = data, LSB first    P = stop (always high)")
    print()
    for line in render_waveform(frame_sequence(data, stopbits), cols).splitlines():
        print(("  " + line).rstrip())


