def chisel_bit_period(clock: int, baud: int) -> int:
    """Clock cycles per bit for chisel-lib's UART.

    It loads a down-counter with round(clock/baud) - 1 and counts through
    zero, so a bit lasts one cycle more than the constant in the Verilog.
    Checked against both generated files in this repo: 115200 -> 0x363 (867)
    and 921600 -> 0x6c (108).
    """
    return max(1, (clock + baud // 2) // baud)


def find_verilog(path: str) -> str:
    """Resolve the Verilog path, falling back to the repo root.

    The generated files live next to build.sbt, so the default works whether
    the script is run from the project root or from scripts/.
    """
    if os.path.isfile(path) or os.path.isabs(path):
        return path
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, path)
    return os.path.normpath(root) if os.path.isfile(root) else path


def read_verilog_period(path: str) -> int | None:
    """Bit period from generated Verilog, or None if it cannot be read.

    chisel-lib emits two reload constants: the bit period minus one, and a
    1.5x one for the receiver's mid-bit sampling.  The smaller is the bit.
    """
    try:
        with open(find_verilog(path), "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    except OSError:
        return None
    consts = {int(m, 16) for m in re.findall(r"cntReg <= \d+.h([0-9a-fA-F]+)", text)}
    consts.discard(0)
    return min(consts) + 1 if consts else None


def nearest_standard_baud(baud: float, tol: float = 0.02) -> int | None:
    best = min(STANDARD_BAUDS, key=lambda b: abs(b - baud))
    return best if abs(best - baud) / best <= tol else None


def project_baud(clock: int, verilog: str) -> int | None:
    """The baud the generated Verilog was built for, if we can tell."""
    period = read_verilog_period(verilog)
    if period is None:
        return None
    return nearest_standard_baud(clock / period)


def divider_report(clock: int, baud: int, verilog: str | None) -> dict:
    """Everything worth knowing about whether this baud rate is achievable."""
    period = chisel_bit_period(clock, baud)
    from_verilog = read_verilog_period(verilog) if verilog else None
    actual = clock / period
    error = (actual - baud) / baud
    return {
        "clock": clock,
        "baud": baud,
        "period": period,
        "verilog_period": from_verilog,
        "verilog_path": verilog,
        "actual": actual,
        "error": error,
        # Both ends drift and share one budget, so a host that is spot on
        # still leaves only MAX_DRIFT/LAST_SAMPLE_BIT for the FPGA.
        "drift_at_stop": abs(error) * LAST_SAMPLE_BIT,
        "margin": MAX_DRIFT / LAST_SAMPLE_BIT,
    }


def print_divider_report(r: dict) -> list[str]:
    """Print the baud maths; return warnings for the closing verdict."""
    warnings: list[str] = []
    print(f"  system clock      {r['clock'] / 1e6:g} MHz")
    print(f"  requested baud    {r['baud']:,}")
    print(f"  bit period        {r['period']} clock cycles "
          f"({r['period'] / r['clock'] * 1e9:.1f} ns)")

    if r["verilog_period"] is not None:
        name = os.path.basename(r["verilog_path"])
        if r["verilog_period"] == r["period"]:
            print(f"  {name:<17} {r['verilog_period']} cycles per bit (agrees)")
        else:
            built_for = r["clock"] / r["verilog_period"]
            print(f"  {name:<17} {r['verilog_period']} cycles per bit "
                  f"-> {built_for:,.0f} baud")
            warnings.append(
                f"{name} was built for about {built_for:,.0f} baud, not {r['baud']:,}. "
                f"Re-generate the Verilog, or use "
                f"--baud {nearest_standard_baud(built_for) or round(built_for)}."
            )

    print(f"  actual baud       {r['actual']:,.1f}  ({r['error'] * 100:+.3f}%)")
    print(f"  drift at stop bit {r['drift_at_stop'] * 100:.2f}% of a bit cell "
          f"(mis-samples past {MAX_DRIFT * 100:.0f}%)")
    print(f"  budget            baud error up to {r['margin'] * 100:.2f}%, "
          f"shared with the host adapter")

    if abs(r["error"]) > r["margin"]:
        warnings.append(
            f"baud error {r['error'] * 100:+.2f}% blows the "
            f"{r['margin'] * 100:.1f}% budget -- the stop bit lands in the wrong cell."
        )
    elif abs(r["error"]) > r["margin"] / 2:
        warnings.append(
            f"baud error {r['error'] * 100:+.2f}% eats over half the timing budget, "
            f"leaving little room for the host adapter's own error."
        )
    else:
        print("  verdict           comfortably inside the timing budget")
    return warnings


